-- 3) Long-term schedule normalization to replace JSONB booking_date filters.
-- Recommended design: schedule rules in a child table, then derive bookable slots.
create table if not exists public.court_schedule_rules (
  schedule_rule_id bigint generated by default as identity primary key,
  courtid integer not null references public.courts(courtid) on delete cascade,
  playingcourtid bigint references public.playingcourt(playingcourtid) on delete cascade,
  day_of_week smallint not null check (day_of_week between 0 and 6),
  valid_from date not null,
  valid_to date,
  start_time time not null,
  end_time time not null,
  is_available boolean not null default true,
  created_at timestamptz not null default now()
);

create index if not exists idx_court_schedule_rules_lookup
  on public.court_schedule_rules (courtid, playingcourtid, day_of_week, valid_from, valid_to);

