-- 1) Enforce double-booking prevention at the database layer.
create extension if not exists btree_gist;

drop index if exists public.courtbooking_no_overlap;

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'courtbooking_no_overlap_excl'
      and conrelid = 'public.courtbooking'::regclass
  ) then
    alter table public.courtbooking
      add constraint courtbooking_no_overlap_excl
      exclude using gist (
        playingcourtid with =,
        tsrange(start_timestamp, end_timestamp, '[)') with &&
      )
      where (
        playingcourtid is not null
        and bookingstatus = 'upcoming'::sessionstatus
      );
  end if;
end $$;

-- 2) Migrate next_gap_id defaults to native IDENTITY columns.
-- next_gap_id scans for holes and can serialize inserts under concurrency.
create or replace function public.migrate_gap_id_default_to_identity(p_table regclass, p_column name)
returns void
language plpgsql
as $$
declare
  default_expr text;
  max_id bigint;
  seq_name text;
begin
  select pg_get_expr(d.adbin, d.adrelid)
    into default_expr
  from pg_attrdef d
  join pg_attribute a
    on a.attrelid = d.adrelid
   and a.attnum = d.adnum
  where d.adrelid = p_table
    and a.attname = p_column;

  if default_expr is null or default_expr not like 'next_gap_id(%' then
    raise notice 'Skipping %.% because default is %', p_table::text, p_column, coalesce(default_expr, '<none>');
    return;
  end if;

  execute format('select coalesce(max(%I), 0) from %s', p_column, p_table) into max_id;
  execute format('alter table %s alter column %I drop default', p_table, p_column);
  execute format('alter table %s alter column %I add generated by default as identity', p_table, p_column);

  select pg_get_serial_sequence(p_table::text, p_column::text) into seq_name;
  perform setval(seq_name, max_id + 1, false);
end $$;

